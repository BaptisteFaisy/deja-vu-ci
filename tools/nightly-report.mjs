#!/usr/bin/env node
/**
 * tools/nightly-report.mjs — the nightly proof report generator.
 *
 * The nightly workflow replays the sample dataset, re-measures accuracy on
 * the labelled corpus, checks repository integrity, and publishes
 * `docs/NIGHTLY-REPORT.md` with the real numbers. This tool builds the
 * report; the workflow only orchestrates (run the gates, call this tool,
 * publish the file when it changed).
 *
 * Four offline modes:
 *   collect --out-dir DIR   replay + measurement JSON (needs the built engine)
 *   checks  --out FILE      integrity JSON (Forge manifests, SBOM, site bundle)
 *   tests   --vitest FILE   normalises the JSON report of Vitest
 *   render  --inputs DIR    Markdown report built from the JSON files above
 *
 * `render` is pure: the same JSON always gives the same Markdown, byte for
 * byte. The numbers come from the very same code as the gates — the replay
 * engine (`tools/replay.mjs`) and the accuracy measurement
 * (`tools/eval-accuracy.mjs`), whose helpers are imported here — so the
 * published proof cannot drift from the verdict of the run.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { THRESHOLDS, evaluateCorpus, percent, readCorpus } from './eval-accuracy.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const repoRoot = path.resolve(here, '..');

/** JSON files produced by `collect` / `checks`, consumed by `render`. */
export const INPUT_FILES = {
  replay: 'replay.json',
  measurement: 'measurement.json',
  tests: 'tests.json',
  checks: 'checks.json',
};

const SAMPLE_DATASET = path.join(repoRoot, 'data', 'sample', 'occurrences.json');

/* ------------------------------------------------------------------ *
 * Pure rendering: JSON in, Markdown out.
 * ------------------------------------------------------------------ */

/** One Markdown table row. */
function row(cells) {
  return `| ${cells.join(' | ')} |`;
}

/** A Markdown table from its headers and its rows. */
function table(headers, rows) {
  return [row(headers), row(headers.map(() => '---')), ...rows.map(row)].join('\n');
}

/** English label of a key (`already-fixed` → `already fixed`). */
function human(text) {
  return String(text ?? '').replace(/[-_]/g, ' ');
}

/** Counts how many items share each key returned by `keyOf`. */
function tally(items, keyOf) {
  const counts = {};
  for (const item of items) {
    const value = keyOf(item) ?? 'unknown';
    counts[value] = (counts[value] ?? 0) + 1;
  }
  return counts;
}

/** "a (2), b (1) and c (3)" — readable list of the counted keys. */
function summary(counts) {
  const entries = Object.entries(counts).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  if (entries.length === 0) return 'none';
  if (entries.length === 1) return `${human(entries[0][0])} (${entries[0][1]})`;
  const last = entries.pop();
  return `${entries.map(([key, count]) => `${human(key)} (${count})`).join(', ')} and ${human(last[0])} (${last[1]})`;
}

/** Header of the report: what ran, when, from which commit. */
function renderHeader(meta) {
  const parts = [`Generated on **${meta.date}** by [\`.github/workflows/nightly.yml\`](../.github/workflows/nightly.yml)`];
  if (meta.commit) parts.push(`commit \`${meta.commit}\``);
  if (meta.runUrl) parts.push(`[run ${meta.runId ?? ''}](${meta.runUrl})`);
  if (meta.runner) parts.push(`runner \`${meta.runner}\``);
  return [
    '# Nightly proof — Déjà-vu CI',
    '',
    parts.join(' · '),
    '',
    '_Do not edit this file by hand: the next nightly run regenerates it. What it proves — and what it does not — is described in [`docs/NIGHTLY.md`](NIGHTLY.md)._',
  ].join('\n');
}

/** Problems found in the inputs; empty when everything is green. */
export function findProblems(inputs) {
  const problems = [];
  const tests = inputs.tests ?? {};
  if (tests.total === undefined) problems.push('test summary missing');
  else if (tests.failed > 0) problems.push(`${tests.failed} failing test(s)`);
  for (const breach of inputs.measurement?.breaches ?? []) problems.push(breach);
  for (const check of inputs.checks?.checks ?? []) {
    if (!check.ok) problems.push(`${check.label} — ${check.detail}`);
  }
  return problems;
}

/** The verdict section: one line, then the problems when there are some. */
function renderVerdict(inputs) {
  const problems = findProblems(inputs);
  const tests = inputs.tests ?? {};
  const lines = ['## Verdict', ''];
  if (problems.length === 0) {
    const count = tests.total === undefined ? 'the whole' : `${tests.passed}/${tests.total}`;
    lines.push(`**PASS** — ${count} tests green, sample replay and accuracy measurement above their thresholds, integrity checks green.`);
  } else {
    lines.push('**FAIL** — the run did not meet every gate:');
    lines.push('');
    for (const problem of problems) lines.push(`- ${problem}`);
  }
  return lines.join('\n');
}

/** The test suite section, from the Vitest JSON report. */
function renderTests(tests) {
  const rows = [
    ['Tests', tests.total === undefined ? 'not measured' : `${tests.passed} passed / ${tests.total} total`],
    ['Failing tests', String(tests.failed ?? 0)],
    ['Test files', String(tests.files ?? 0)],
    ['Duration', tests.durationMs === undefined ? 'not measured' : `${(tests.durationMs / 1000).toFixed(1)} s`],
  ];
  return ['## 1. Test suite (`npx vitest run`)', '', table(['Measure', 'Value'], rows)].join('\n');
}

/** The sample replay section, from the replay JSON. */
function renderReplay(replay) {
  const rows = [
    ['Dataset', `${replay.dataset ?? 'unknown'} — ${replay.description ?? ''}`.trim()],
    ['Occurrences replayed', String(replay.occurrences ?? 0)],
    ['Replay time', `${Math.round(replay.elapsedMs ?? 0)} ms`],
    ['Signatures memorised', String(replay.signatures ?? 0)],
    ['Tickets created', String(replay.tickets?.create ?? 0)],
  ];
  return [
    '## 2. Sample replay (`npm run replay`)',
    '',
    table(['Measure', 'Value'], rows),
    '',
    `Diagnostics — ${summary(replay.byKind ?? {})}.`,
    '',
    `Categories of the memorised signatures — ${summary(replay.byCategory ?? {})}.`,
  ].join('\n');
}

/** The accuracy measurement section, from the measurement JSON. */
function renderMeasurement(measurement) {
  const rows = [
    [
      'Correct grouping',
      percent(measurement.groupingAccuracy ?? 0),
      `≥ ${percent(THRESHOLDS.grouping)}`,
      (measurement.groupingAccuracy ?? 0) >= THRESHOLDS.grouping ? 'OK' : 'BELOW THRESHOLD',
    ],
    [
      'False "flaky"',
      percent(measurement.falseFlakyRate ?? 0),
      `< ${percent(THRESHOLDS.falseFlaky)}`,
      (measurement.falseFlakyRate ?? 0) < THRESHOLDS.falseFlaky ? 'OK' : 'ABOVE THRESHOLD',
    ],
    [
      'Correct category',
      percent(measurement.categoryAccuracy ?? 0),
      `≥ ${percent(THRESHOLDS.category)}`,
      (measurement.categoryAccuracy ?? 0) >= THRESHOLDS.category ? 'OK' : 'BELOW THRESHOLD',
    ],
  ];
  const corpus = `${measurement.corpus ?? 'unknown'} — ${measurement.failures ?? 0} labelled failures, ${measurement.groups ?? 0} groups, ${measurement.signatures ?? 0} signatures`;
  return [
    '## 3. Accuracy measurement (`npm run eval`)',
    '',
    table(['Measure', 'Value', 'Threshold', 'Verdict'], rows),
    '',
    `Corpus: ${corpus}.`,
  ].join('\n');
}

/** The integrity section, from the checks JSON. */
function renderChecks(checks) {
  const rows = (checks?.checks ?? []).map((check) => [
    check.label,
    check.ok ? 'OK' : 'FAILED',
    check.detail ?? '',
  ]);
  const body = rows.length > 0 ? table(['Check', 'Result', 'Detail'], rows) : '_no check ran_';
  return ['## 4. Repository integrity', '', body].join('\n');
}

/** The closing section: what this report does not prove. */
function renderLimits() {
  return [
    '## What this report does not prove',
    '',
    '- The real rendering of the two Forge apps (the UI of the Capteur and of the Cerveau) is not exercised here.',
    '- No Bitbucket call, no Jira call and no LLM call happen in this run: the numbers come from local fixtures.',
    '- The timings are those of a self-hosted runner under load, not of the Atlassian infrastructure.',
    '',
    'See [`docs/NIGHTLY.md`](NIGHTLY.md) for the full reading of this proof.',
  ].join('\n');
}

/**
 * Builds the Markdown report from the collected JSON.
 *
 * Pure: the same inputs always give the same output.
 */
export function renderReport(inputs) {
  const meta = inputs.meta ?? {};
  return [
    renderHeader(meta),
    renderVerdict(inputs),
    renderTests(inputs.tests ?? {}),
    renderReplay(inputs.replay ?? {}),
    renderMeasurement(inputs.measurement ?? {}),
    renderChecks(inputs.checks ?? {}),
    renderLimits(),
  ].join('\n\n') + '\n';
}

/* ------------------------------------------------------------------ *
 * Collection: the engine and the repository.
 * ------------------------------------------------------------------ */

/** Replays the sample dataset with the engine and returns the JSON payload. */
export async function collectReplay(engine, dataset) {
  const result = await engine.replay(dataset);
  return {
    dataset: result.datasetName ?? dataset?.name ?? 'unknown',
    description: dataset?.description ?? '',
    occurrences: result.occurrences ?? 0,
    elapsedMs: result.elapsedMs ?? 0,
    signatures: (result.signatures ?? []).length,
    tickets: tally(result.tickets ?? [], (ticket) => ticket?.kind),
    byKind: tally(result.diagnostics ?? [], (entry) => entry?.diagnostic?.kind),
    byCategory: tally(result.signatures ?? [], (signature) => signature?.category),
  };
}

/** Measures the labelled corpus with the engine and returns the JSON payload. */
export function collectMeasurement(engine, corpus) {
  const { rows, grouping, flaky, categoryAccuracy, breaches } = evaluateCorpus(engine, corpus);
  return {
    corpus: corpus?.name ?? 'unknown',
    failures: rows.length,
    groups: grouping.groups,
    signatures: flaky.signatures,
    groupingAccuracy: grouping.accuracy,
    falseFlakyRate: flaky.rate,
    falseFlakyFlagged: flaky.flagged,
    categoryAccuracy,
    thresholds: THRESHOLDS,
    breaches,
  };
}

/** Normalises the JSON report of Vitest into the handful of numbers we show. */
export function summarizeVitest(report) {
  const results = report?.testResults ?? [];
  // Wall-clock span of the run: the files run in parallel, so summing their
  // own durations would overstate the time the suite took.
  const starts = results.map((file) => file?.startTime ?? 0).filter((value) => value > 0);
  const ends = results.map((file) => file?.endTime ?? 0).filter((value) => value > 0);
  const duration = starts.length > 0 && ends.length > 0 ? Math.max(...ends) - Math.min(...starts) : 0;
  return {
    total: report?.numTotalTests ?? 0,
    passed: report?.numPassedTests ?? 0,
    failed: report?.numFailedTests ?? 0,
    pending: report?.numPendingTests ?? 0,
    files: results.length,
    suites: report?.numTotalTestSuites ?? 0,
    durationMs: Math.max(0, Math.round(duration)),
  };
}

/** Checks the Forge manifests against the official schema. */
function checkManifests(validator) {
  const failures = [];
  let detail = '';
  try {
    for (const file of validator.MANIFESTS) {
      const result = validator.validateManifest(file);
      if (!result.ok) failures.push(path.relative(repoRoot, file));
    }
    detail =
      failures.length === 0
        ? `${validator.MANIFESTS.length} manifest(s) conform to @forge/manifest`
        : `not conform: ${failures.join(', ')}`;
  } catch (error) {
    failures.push('unreadable');
    detail = `manifest tool unavailable: ${error.message}`;
  }
  return { id: 'manifests', label: 'Forge manifests (official schema)', ok: failures.length === 0, detail };
}

/** Checks that the committed SBOM still matches the workspace manifests. */
async function checkSbom() {
  const sbom = await import('./sbom.mjs');
  const committed = readFileSync(sbom.OUTPUT_PATH, 'utf8');
  const fresh = sbom.renderSbom(sbom.buildSbom());
  return {
    id: 'sbom',
    label: 'SBOM up to date',
    ok: committed === fresh,
    detail:
      committed === fresh
        ? 'docs/SBOM.json matches the workspace manifests'
        : 'docs/SBOM.json differs from the workspace manifests',
  };
}

/** Checks that the published site bundle still matches its sources. */
async function checkSiteBundle() {
  const site = await import('./build-site.mjs');
  const manifest = JSON.parse(readFileSync(path.join(site.PUBLIC, 'build-manifest.json'), 'utf8'));
  const fresh = site.fingerprint();
  return {
    id: 'site-bundle',
    label: 'Site bundle fingerprint',
    ok: manifest.empreinte === fresh,
    detail:
      manifest.empreinte === fresh
        ? 'site/public matches its sources'
        : 'site/public is older than its sources (rebuild the site)',
  };
}

/** Runs every integrity check and returns the JSON payload. */
export async function collectChecks() {
  const validator = await import('./validate-manifest.mjs');
  const checks = [checkManifests(validator), await checkSbom(), await checkSiteBundle()];
  return { checks };
}

/* ------------------------------------------------------------------ *
 * Command line.
 * ------------------------------------------------------------------ */

/** Parses `--flag value` arguments into a plain object. */
export function parseArgs(argv) {
  const args = {};
  for (let index = 0; index < argv.length; index += 1) {
    const item = argv[index];
    if (!item.startsWith('--')) continue;
    const name = item.slice(2);
    const next = argv[index + 1];
    if (next === undefined || next.startsWith('--')) args[name] = true;
    else {
      args[name] = next;
      index += 1;
    }
  }
  return args;
}

/** Writes a JSON payload, creating the parent directory when needed. */
function writeJson(file, payload) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
}

/** `collect`: replays the sample and measures the corpus, then writes the JSON. */
async function runCollect(args) {
  const { loadEngine, missingEntryPoints } = await import('./lib/engine.mjs');
  const engine = await loadEngine();
  const missing = missingEntryPoints(engine);
  if (missing.length > 0) {
    console.error(`engine incomplete: ${missing.join(', ')} — run "npm run build" first`);
    process.exit(2);
  }
  const dataset = JSON.parse(readFileSync(SAMPLE_DATASET, 'utf8'));
  const outDir = args['out-dir'];
  writeJson(path.join(outDir, INPUT_FILES.replay), await collectReplay(engine, dataset));
  writeJson(path.join(outDir, INPUT_FILES.measurement), collectMeasurement(engine, readCorpus()));
  console.log(`collected: ${outDir}`);
}

/** `checks`: runs the integrity checks and writes the JSON payload. */
async function runChecks(args) {
  const payload = await collectChecks();
  writeJson(args.out, payload);
  for (const check of payload.checks) {
    console.log(`${check.ok ? 'OK' : 'FAILED'} ${check.label} — ${check.detail}`);
  }
  if (payload.checks.some((check) => !check.ok)) process.exit(1);
}

/** `tests`: normalises the JSON report of Vitest into the report payload. */
function runTests(args) {
  const report = JSON.parse(readFileSync(args.vitest, 'utf8'));
  const summary = summarizeVitest(report);
  writeJson(args.out, summary);
  console.log(
    `tests: ${summary.passed}/${summary.total} passed, ${summary.failed} failed, ` +
      `${summary.files} file(s), ${(summary.durationMs / 1000).toFixed(1)} s`,
  );
  if (summary.failed > 0) process.exit(1);
}

/** `render`: builds the Markdown report from the collected JSON files. */
function runRender(args) {
  const dir = args.inputs;
  const read = (name) => JSON.parse(readFileSync(path.join(dir, name), 'utf8'));
  const inputs = {
    replay: read(INPUT_FILES.replay),
    measurement: read(INPUT_FILES.measurement),
    tests: read(INPUT_FILES.tests),
    checks: read(INPUT_FILES.checks),
    meta: {
      date: args.date ?? new Date().toISOString().slice(0, 10),
      commit: args.commit ?? process.env.GITHUB_SHA ?? '',
      runId: process.env.GITHUB_RUN_ID ?? '',
      runUrl: process.env.GITHUB_RUN_URL ?? '',
      runner: process.env.RUNNER_NAME ?? '',
    },
  };
  const markdown = renderReport(inputs);
  writeFileSync(args.out, markdown, 'utf8');
  console.log(`report: ${args.out} (${markdown.length} characters)`);
  if (findProblems(inputs).length > 0) process.exit(1);
}

/** Entry point of the command line. */
async function main(argv) {
  const [mode, ...rest] = argv;
  const args = parseArgs(rest);
  if (mode === 'collect') await runCollect(args);
  else if (mode === 'checks') await runChecks(args);
  else if (mode === 'tests') runTests(args);
  else if (mode === 'render') runRender(args);
  else {
    console.error(
      'usage: nightly-report.mjs collect --out-dir DIR | checks --out FILE | ' +
        'tests --vitest FILE --out FILE | render --inputs DIR --out FILE',
    );
    process.exit(2);
  }
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) await main(process.argv.slice(2));
